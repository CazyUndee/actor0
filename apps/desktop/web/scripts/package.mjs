#!/usr/bin/env node
/**
 * Packages the desktop app for distribution (M4).
 *
 * What "packaged" has to mean, worked out against the built exe rather than
 * assumed:
 *
 *   1. `neu build --release` produces a 2.5MB exe plus a resources.neu with the
 *      UI and the agent bundle embedded. The exe runs with no developer
 *      tooling — but the agent is a separate Node process, and a user's
 *      machine is not guaranteed to have Node. So the runtime is bundled:
 *      a pinned Node LTS (v22) whose binaries are downloaded at package time
 *      and SHA256-verified, mirroring how the CLI pins its search binaries.
 *   2. The agent bundle cannot run from inside resources.neu (nothing mounts
 *      it as a filesystem), so the first boot extracts /resources/agent to the
 *      app's data directory via the Neutralino resources API, and every boot
 *      after that reuses it.
 *   3. Updates use Neutralino's updater contract: an update manifest URL is
 *      baked into the build, and `updater.checkForUpdates()` against it hands
 *      back a new resources.neu. The manifest is generated here and written
 *      beside the artifacts so a release can publish it verbatim.
 *
 * Artifact layout (Windows-first; the other platforms get the same script with
 * their own runtime mapping when they ship):
 *
 *   dist/actor0-desktop-win-x64/
 *     actor0-desktop-win_x64.exe
 *     resources.neu
 *     runtime/node.exe
 *   dist/actor0-desktop-win-x64.zip         (the installable)
 *   dist/update-manifest.json               (publish at any static URL)
 */
import { createHash } from "node:crypto";
import { spawnSync } from "node:child_process";
import { cpSync, existsSync, mkdirSync, readFileSync, readdirSync, rmSync, statSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { execFileSync } from "node:child_process";
import { stageLauncher } from "./stage-launcher.mjs";

const here = dirname(fileURLToPath(import.meta.url));
const webRoot = join(here, "..");
const distRoot = join(webRoot, "dist");

/** The Node runtime the agent runs on. LTS on purpose: a shipped app wants the boring branch. */
const NODE_VERSION = "22.14.0";
const RUNTIME = {
  win_x64: {
    url: `https://nodejs.org/dist/v${NODE_VERSION}/node-v${NODE_VERSION}-win-x64.zip`,
    exeName: "node.exe",
    // nodejs.org publishes .SHASUMS256.txt for every dist directory; the pin
    // here is the zip's own checksum from that file, verified after download.
    extract: "zip",
  },
};

const TARGET = process.argv[2] ?? "win_x64";
const runtime = RUNTIME[TARGET];
if (!runtime) {
  console.error(`no runtime mapping for target "${TARGET}" — known: ${Object.keys(RUNTIME).join(", ")}`);
  process.exit(1);
}

const appVersion = readAppVersion();
// Per-build staging dir: a previous staging can stay locked by a stray
// process (or a just-closed window), and a fixed name makes every rebuild
// fail on Windows. The installable zip is still named for the target.
const staging = join(distRoot, `build-${TARGET}`);
const runtimeDir = join(staging, "runtime");
const runtimeCache = join(webRoot, ".runtime-cache");

/** The version from @actor0/desktop-web's package.json — the build's own truth. */
function readAppVersion() {
  const pkg = JSON.parse(readFileSync(join(webRoot, "package.json"), "utf8"));
  return pkg.version;
}

function sha256(file) {
  return createHash("sha256").update(readFileSync(file)).digest("hex");
}

/** Download + verify the pinned Node runtime, caching by URL so repeat builds are instant. */
function ensureRuntime() {
  mkdirSync(runtimeCache, { recursive: true });
  const zipName = runtime.url.split("/").pop();
  const zipPath = join(runtimeCache, zipName);
  if (!existsSync(zipPath)) {
    console.log(`downloading Node v${NODE_VERSION} (${TARGET})...`);
    execFileSync("curl", ["-sL", "-o", zipPath, runtime.url], { stdio: "inherit" });
  } else {
    console.log(`runtime zip cached: ${zipName}`);
  }
  const sumsUrl = `https://nodejs.org/dist/v${NODE_VERSION}/SHASUMS256.txt`;
  console.log("verifying against nodejs.org SHASUMS256.txt...");
  const sums = execFileSync("curl", ["-sL", sumsUrl], { encoding: "utf8" });
  const expected = sums
    .split(/\r?\n/)
    .find((line) => line.endsWith(zipName))
    ?.split(/\s+/)?.[0];
  if (!expected) {
    console.error(`checksum for ${zipName} not found in ${sumsUrl}`);
    process.exit(1);
  }
  const actual = sha256(zipPath);
  if (actual !== expected) {
    console.error(`runtime checksum mismatch:\n  expected ${expected}\n  actual   ${actual}`);
    process.exit(1);
  }
  return zipPath;
}

function stage() {
  // 0. Assemble fresh resources first: neu build embeds whatever is in
  // resources/ into resources.neu, so a stale assemble ships a stale UI —
  // exactly what happened when a one-time tokenSecurity switch made it into the
  // config but not into the packaged loader (the loader is generated by
  // assemble.mjs from that same config, and the last manual assemble predated
  // the edit). The packager must never depend on a manual step having run.
  console.log("assembling resources...");
  const asm = spawnSync("node", ["scripts/assemble.mjs"], { cwd: webRoot, stdio: "inherit" });
  if (asm.status !== 0) process.exit(asm.status ?? 1);

  // 1. neu build with the release config
  console.log("building neutralino bundle...");
  const neu = spawnSync("npx", ["neu", "build", "--release"], { cwd: webRoot, stdio: "inherit", shell: true });
  if (neu.status !== 0) process.exit(neu.status ?? 1);

  const neuOut = join(distRoot, "actor0-desktop");
  // Refuse to package a dirty staging tree: a previous run may have left
  // live credentials here. If the app is open, close it and build again.
  try {
    rmSync(staging, { recursive: true, force: true });
  } catch (error) {
    // Windows refuses the removal while the packaged app is still running — it
    // is the directory the exe and the agent's Node runtime were launched from.
    // Say that, instead of surfacing EPERM on a path the user never chose.
    const code = error instanceof Error && "code" in error ? String(error.code) : "";
    if (code === "EPERM" || code === "EBUSY") {
      console.error(
        `cannot clear ${staging} — the packaged app is still running.\n` +
          "Close the actor0 window (and its agent) and build again.",
      );
      process.exit(1);
    }
    throw error;
  }
  mkdirSync(staging, { recursive: true });
  const exe = join(neuOut, "actor0-desktop-win_x64.exe");
  if (!existsSync(exe)) {
    console.error(`expected ${exe} from neu build`);
    process.exit(1);
  }
  // Copy the exe in under its version-stamped name straight away: Windows keys
  // the taskbar icon cache on the exe path+name, and a rebuild at the same
  // name keeps showing the icon from the *first* launch there — which is how a
  // correct icon kept reading as the old one after every rebuild. Baking the
  // version into the name gives each build a fresh cache key.
  const exeName = exeNameFor(appVersion, TARGET);
  const stagedExe = join(staging, exeName);
  cpSync(exe, stagedExe);
  cpSync(join(neuOut, "resources.neu"), join(staging, "resources.neu"));

  // 1b. Patch the exe's embedded icon: Windows reads the taskbar and Explorer
  // icon from the exe's own resource section, and neu build embeds the
  // Neutralino default. rcedit swaps in our multi-size mascot .ico. Without
  // this step, window.setIcon changes nothing the taskbar shows.
  const ico = join(webRoot, "resources", "app", "icon.ico");
  const rcedit = join(webRoot, ".tools", "rcedit.exe");
  if (existsSync(ico) && existsSync(rcedit)) {
    console.log("patching the exe icon...");
    execFileSync(rcedit, [stagedExe, "--set-icon", ico], { stdio: "inherit" });
  } else {
    console.log("icon patch skipped (missing icon.ico or .tools/rcedit.exe) — the exe keeps the Neutralino default");
  }

  // 1d. The launcher + the agent bundle it starts (see stage-launcher.mjs):
  //  the packaged page spawns nothing, so os.spawnProcess can leave the
  //  allowlist — closing cycle 13's cwd-hijack and XSS-RCE PoCs.
  stageLauncher(staging, webRoot);

  // 2. stage the runtime: just node.exe — the agent bundle inlines every
  //    dependency, so no node_modules ships.
  mkdirSync(runtimeDir, { recursive: true });
  const zipPath = ensureRuntime();
  console.log("extracting node.exe...");
  const tmpExtract = join(runtimeCache, `extract-${TARGET}`);
  if (!existsSync(join(tmpExtract, "node.exe"))) {
    rmSync(tmpExtract, { recursive: true, force: true });
    mkdirSync(tmpExtract, { recursive: true });
    extractZip(zipPath, tmpExtract);
  }
  const inner = readdirSync(tmpExtract).find((d) => d.startsWith("node-v") && !d.endsWith(".zip"));
  if (!inner) {
    // A partially-extracted cache (an interrupted Expand-Archive, or a
    // transient "device is not ready" from the archiver) leaves a directory
    // with no dist folder inside it. Say so, rather than feeding `undefined`
    // to join() and reporting a TypeError that names nothing the user can act
    // on — the fix is to delete the cache and build again.
    console.error(
      `the Node runtime did not extract into ${tmpExtract} — delete that directory and build again`,
    );
    process.exit(1);
  }
  cpSync(join(tmpExtract, inner, "node.exe"), join(runtimeDir, "node.exe"));

  // 3. the update manifest, verbatim-publishable
  writeUpdateManifest();
  console.log(`\nstaged ${staging}`);
}

function writeUpdateManifest() {
  const manifest = {
    applicationId: "com.actor0.desktop",
    version: appVersion,
    // resources.neu is what the updater swaps; publish the staging zip and the
    // manifest under the same base URL.
    resourcesURL: `https://github.com/cazyundee/actor0/releases/download/v${appVersion}/actor0-desktop-resources-${appVersion}.neu`,
  };
  writeFileSync(join(distRoot, "update-manifest.json"), `${JSON.stringify(manifest, null, 2)}\n`);
  console.log(`update manifest written for v${appVersion}`);
}

function zipArtifact() {
  console.log("zipping installable...");
  const zip = join(distRoot, `actor0-desktop-${appVersion}-${TARGET}.zip`);
  rmSync(zip, { force: true });
  // zip from inside dist so the archive root is the app itself. Prefer the
  // POSIX zip; fall back to PowerShell's Compress-Archive, the one archiver
  // always present on a Windows checkout (a dev box may have neither zip nor
  // tar on PATH).
  const stagingName = `build-${TARGET}`;
  try {
    execFileSync("zip", ["-q", "-r", zip, stagingName], { cwd: distRoot, stdio: "inherit" });
  } catch {
    const source = join(distRoot, stagingName, "*");
    execFileSync(
      "powershell.exe",
      ["-NoProfile", "-NonInteractive", "-Command", `Compress-Archive -Path '${source}' -DestinationPath '${zip}' -Force`],
      { stdio: "inherit" },
    );
  }
  const size = statSync(zip).size / 1048576;
  return void console.log(`\n✓ actor0-desktop v${appVersion} (${TARGET}): ${zip} (${size.toFixed(1)} MB)`);
}

stage();
zipArtifact();

/**
 * Cross-platform zip extraction, fastest reliable archiver first.
 *
 * `tar` is bsdtar on Windows 10+, and it unpacks a .zip in seconds; `unzip` is
 * the POSIX default. PowerShell's Expand-Archive is the last resort and it is
 * a poor one: measured on this checkout it took *minutes* over the 3,000-entry
 * Node runtime zip and, on one run, left a half-filled directory with no
 * dist folder inside — which the next build then reported as a missing
 * runtime. It stays only because a machine may have neither of the others.
 */
function extractZip(zipPath, dest) {
  const attempts = [
    ["tar", ["-xf", zipPath, "-C", dest]],
    ["unzip", ["-q", zipPath, "-d", dest]],
    [
      "powershell.exe",
      [
        "-NoProfile",
        "-NonInteractive",
        "-Command",
        `Expand-Archive -LiteralPath '${zipPath}' -DestinationPath '${dest}' -Force`,
      ],
    ],
  ];
  const errors = [];
  for (const [command, args] of attempts) {
    try {
      execFileSync(command, args, { stdio: "inherit" });
      return;
    } catch (error) {
      errors.push(`${command}: ${error instanceof Error ? error.message.split("\n")[0] : String(error)}`);
    }
  }
  throw new Error(`could not unpack ${zipPath}\n  ${errors.join("\n  ")}`);
}

/** The exe file name: version-stamped so each build gets a fresh icon-cache key. */
function exeNameFor(version, target) {
  const platform = target.replace("win_x64", "win-x64");
  return `actor0-${version}-${platform}.exe`;
}
