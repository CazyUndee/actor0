/**
 * Build the Windows setup executable with NSIS.
 *
 * NSIS is used instead of Inno Setup because Inno now asks for a paid
 * commercial licence. NSIS is zlib-licensed for any use and is what the
 * Windows runner already has available through Chocolatey.
 *
 * The installer is per-user: no UAC prompt, no machine-wide service, and the
 * install lands under %LOCALAPPDATA%\Programs\actor0. User state remains in
 * %USERPROFILE%\.actor0 and is deliberately left behind on uninstall.
 */
import { execFileSync } from "node:child_process";
import { existsSync, rmSync, writeFileSync } from "node:fs";
import { delimiter, join } from "node:path";

/** NSIS expands $ in strings; a path may legitimately contain one. */
function nsiPath(path) {
  return path.replace(/\$/g, "$$$$");
}

/**
 * The generated NSIS script. Exported so the test can assert the parts that
 * are easy to lose in a template edit: the per-user install root, the VBS
 * shortcut, the uninstall entry, and the running-app guard.
 */
export function nsisScript({ staging, outFile, version, binaryName, icon }) {
  const version4 = `${version.split("-")[0]}.0`;
  const quote = '$\\"';
  return [
    "; Generated by apps/desktop/web/scripts/nsis.mjs. Do not edit.",
    "Unicode true",
    "SetCompressor /SOLID lzma",
    "RequestExecutionLevel user",
    'Name "actor0"',
    `OutFile "${nsiPath(outFile)}"`,
    'InstallDir "$LOCALAPPDATA\\Programs\\actor0"',
    'InstallDirRegKey HKCU "Software\\actor0" "InstallLocation"',
    "",
    `!define APP_VERSION "${version}"`,
    `!define APP_BINARY "${binaryName}"`,
    `!define STAGE "${nsiPath(staging)}"`,
    `!define ICON "${nsiPath(icon)}"`,
    `VIProductVersion "${version4}"`,
    'VIAddVersionKey /LANG=1033 "ProductName" "actor0"',
    'VIAddVersionKey /LANG=1033 "FileDescription" "actor0 desktop installer"',
    `VIAddVersionKey /LANG=1033 "FileVersion" "${version}"`,
    `VIAddVersionKey /LANG=1033 "ProductVersion" "${version}"`,
    'VIAddVersionKey /LANG=1033 "LegalCopyright" "Copyright (c) 2026 CazyUndee"',
    "",
    '!include "MUI2.nsh"',
    "!define MUI_ABORTWARNING",
    '!define MUI_ICON "${ICON}"',
    '!define MUI_UNICON "${ICON}"',
    "",
    "!insertmacro MUI_PAGE_WELCOME",
    "!insertmacro MUI_PAGE_DIRECTORY",
    "!insertmacro MUI_PAGE_INSTFILES",
    '!define MUI_FINISHPAGE_RUN "$INSTDIR\\start-actor0.vbs"',
    '!define MUI_FINISHPAGE_RUN_TEXT "Launch actor0"',
    "!insertmacro MUI_PAGE_FINISH",
    "",
    "!insertmacro MUI_UNPAGE_CONFIRM",
    "!insertmacro MUI_UNPAGE_INSTFILES",
    "",
    '!insertmacro MUI_LANGUAGE "English"',
    "",
    "Function .onInit",
    '  ReadRegStr $0 HKCU "Software\\actor0" "InstallLocation"',
    '  StrCmp $0 "" done',
    '  IfFileExists "$0\\${APP_BINARY}" 0 done',
    "  ClearErrors",
    '  FileOpen $1 "$0\\${APP_BINARY}" a',
    "  IfErrors running",
    "  FileClose $1",
    "  Goto done",
    "running:",
    '  MessageBox MB_OK|MB_ICONSTOP "actor0 is running. Close the actor0 window, then run the installer again."',
    "  Abort",
    "done:",
    "FunctionEnd",
    "",
    'Section "actor0" SecMain',
    '  SetOutPath "$INSTDIR"',
    '  File /r "${STAGE}\\*"',
    '  WriteUninstaller "$INSTDIR\\Uninstall.exe"',
    "",
    '  CreateDirectory "$SMPROGRAMS\\actor0"',
    '  CreateShortCut "$SMPROGRAMS\\actor0\\actor0.lnk" "$INSTDIR\\start-actor0.vbs" "" "$INSTDIR\\${APP_BINARY}" 0',
    '  CreateShortCut "$SMPROGRAMS\\actor0\\Uninstall actor0.lnk" "$INSTDIR\\Uninstall.exe"',
    '  ; Root-level shortcut so Windows Start search indexes "actor0" directly.',
    '  CreateShortCut "$SMPROGRAMS\\actor0.lnk" "$INSTDIR\\start-actor0.vbs" "" "$INSTDIR\\${APP_BINARY}" 0',
    "",
    '  WriteRegStr HKCU "Software\\actor0" "InstallLocation" "$INSTDIR"',
    '  WriteRegStr HKCU "Software\\Microsoft\\Windows\\CurrentVersion\\Uninstall\\actor0" "DisplayName" "actor0"',
    '  WriteRegStr HKCU "Software\\Microsoft\\Windows\\CurrentVersion\\Uninstall\\actor0" "DisplayVersion" "' + version + '"',
    '  WriteRegStr HKCU "Software\\Microsoft\\Windows\\CurrentVersion\\Uninstall\\actor0" "Publisher" "actor0"',
    '  WriteRegStr HKCU "Software\\Microsoft\\Windows\\CurrentVersion\\Uninstall\\actor0" "DisplayIcon" "$INSTDIR\\${APP_BINARY},0"',
    '  WriteRegStr HKCU "Software\\Microsoft\\Windows\\CurrentVersion\\Uninstall\\actor0" "InstallLocation" "$INSTDIR"',
    '  WriteRegStr HKCU "Software\\Microsoft\\Windows\\CurrentVersion\\Uninstall\\actor0" "UninstallString" "' + quote + '$INSTDIR\\Uninstall.exe' + quote + '"',
    '  WriteRegStr HKCU "Software\\Microsoft\\Windows\\CurrentVersion\\Uninstall\\actor0" "QuietUninstallString" "' + quote + '$INSTDIR\\Uninstall.exe' + quote + ' /S' + '"',
    '  WriteRegStr HKCU "Software\\Microsoft\\Windows\\CurrentVersion\\Uninstall\\actor0" "URLInfoAbout" "https://github.com/CazyUndee/actor0"',
    '  WriteRegDWORD HKCU "Software\\Microsoft\\Windows\\CurrentVersion\\Uninstall\\actor0" "NoModify" 1',
    '  WriteRegDWORD HKCU "Software\\Microsoft\\Windows\\CurrentVersion\\Uninstall\\actor0" "NoRepair" 1',
    "SectionEnd",
    "",
    'Section "Uninstall"',
    '  Delete "$SMPROGRAMS\\actor0.lnk"',
    '  Delete "$SMPROGRAMS\\actor0\\actor0.lnk"',
    '  Delete "$SMPROGRAMS\\actor0\\Uninstall actor0.lnk"',
    '  RMDir "$SMPROGRAMS\\actor0"',
    '  DeleteRegKey HKCU "Software\\Microsoft\\Windows\\CurrentVersion\\Uninstall\\actor0"',
    '  DeleteRegKey HKCU "Software\\actor0"',
    '  RMDir /r "$INSTDIR"',
    "SectionEnd",
    "",
  ].join("\n");
}

/** Find the NSIS compiler, including Chocolatey's shim and the default install. */
export function findMakensis() {
  const candidates = [
    process.env.MAKENSIS,
    join(process.env.ProgramFiles || "C:\\Program Files", "NSIS", "makensis.exe"),
    join(process.env["ProgramFiles(x86)"] || "C:\\Program Files (x86)", "NSIS", "makensis.exe"),
    join(process.env.ProgramData || "C:\\ProgramData", "chocolatey", "bin", "makensis.exe"),
  ].filter(Boolean);
  for (const candidate of candidates) if (existsSync(candidate)) return candidate;

  for (const dir of (process.env.PATH || "").split(delimiter)) {
    if (!dir) continue;
    for (const name of ["makensis.exe", "makensis"]) {
      const candidate = join(dir, name);
      if (existsSync(candidate)) return candidate;
    }
  }
  throw new Error(
    "NSIS is required to build the Windows installer.\n" +
      "  Install it with: choco install nsis --version=3.13.0 -y\n" +
      "  or set MAKENSIS to the full path of makensis.exe.",
  );
}

/** Compile the setup executable and leave no generated .nsi in the release output. */
export function buildWindowsInstaller({ staging, outFile, version, binaryName, icon, webRoot }) {
  const scriptPath = join(webRoot, ".tools", "actor0-win_x64.nsi");
  writeFileSync(scriptPath, nsisScript({ staging, outFile, version, binaryName, icon }));
  try {
    execFileSync(findMakensis(), ["/V2", scriptPath], { stdio: "inherit" });
  } finally {
    rmSync(scriptPath, { force: true });
  }
  if (!existsSync(outFile)) throw new Error(`NSIS did not write ${outFile}`);
  return outFile;
}
