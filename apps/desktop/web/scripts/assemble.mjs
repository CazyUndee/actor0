#!/usr/bin/env node
/**
 * Assembles the two halves into the layout the shell serves.
 *
 * `resources/app` is the UI bundle (built by vite), and `resources/agent` is the
 * agent bundle (built by `@actor0/desktop-agent`). Keeping the copy in one small
 * script — rather than two `cp` calls in a package.json string — is what makes
 * the layout a single readable fact, since the shell's config, the spawn command
 * and `neu build` all depend on it being exactly this.
 *
 * It also *generates* `resources/app/neutralino-loader.inline.js` from
 * `src/neutralino-loader.ts` — the same decision table the tests exercise — so
 * the page's loader and the tested policy cannot drift apart. That is the
 * NE_CL_IVCTOKN lesson: half the fix's value is the policy being written down
 * somewhere that breaks loudly when violated.
 */

import { cpSync, existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const webRoot = join(here, "..");
const agentDist = join(webRoot, "..", "agent", "dist", "agent.mjs");
const agentTarget = join(webRoot, "resources", "agent");

if (!existsSync(agentDist)) {
  console.error(`missing ${agentDist} — run: npm --workspace @actor0/desktop-agent run build`);
  process.exit(1);
}

rmSync(agentTarget, { recursive: true, force: true });
mkdirSync(agentTarget, { recursive: true });
cpSync(agentDist, join(agentTarget, "agent.mjs"));

// The Neutralino client library, served beside the page so the same bundle
// works when the shell does not inject it (dev mode through the static server).
const clientLib = join(webRoot, "..", "..", "..", "node_modules", "@neutralinojs", "lib", "dist", "neutralino.js");
if (existsSync(clientLib)) {
  cpSync(clientLib, join(webRoot, "resources", "app", "neutralino.js"));
}

const ui = join(webRoot, "resources", "app", "index.html");
if (!existsSync(ui)) {
  console.error(`missing ${ui} — run: npm --workspace @actor0/desktop-web run build`);
  process.exit(1);
}

// The page-side loader, generated from the module the tests exercise. It must
// run before the app bundle (boot() expects the library decision to be done).
// The security setting is baked in at assemble time because it is a config
// promise, not a runtime discovery: "none" means the globals endpoint carries
// the real token; anything else and connecting a non-injected client is a
// guaranteed NE_CL_IVCTOKN, so the loader loads nothing.
const security = readTokenSecurity();
const loader = `
// GENERATED by scripts/assemble.mjs — edit src/neutralino-loader.ts instead.
// tokenSecurity in neutralino.config.json is ${JSON.stringify(security)}.
(function () {
  var order = ${JSON.stringify(decideOrder(security))};
  if (order === "injected-library-only" || order === "globals-only") {
    // Wait for the token/library globals to exist before deciding below.
  }
  var hasInjectedToken = typeof window.NL_TOKEN !== "undefined" && window.NL_TOKEN !== "";
  if (hasInjectedToken) {
    if (typeof window.Neutralino === "undefined") {
      document.write('<script src="/neutralino.js"><' + '/script>');
    }
    return;
  }
  if (order === "nothing") return; // see neutralino-loader.ts: refuse to load
  document.write('<script src="/__neutralino_globals.js"><' + '/script>');
  document.write('<script>if(typeof window.Neutralino==="undefined"){document.write("<script src=/neutralino.js><\\/script>")}<' + '/script>');
})();
`;
writeFileSync(join(webRoot, "resources", "app", "neutralino-loader.inline.js"), loader);

console.log("resources/ ready: app/ (UI) + agent/agent.mjs (agent core)");

function readTokenSecurity() {
  const config = JSON.parse(readFileSync(join(webRoot, "neutralino.config.json"), "utf8"));
  const value = config.tokenSecurity;
  return value === "none" ? "none" : "one-time";
}

function decideOrder(security) {
  // Mirrors decideClientLoad's no-injection branch; the injected branch is
  // handled at runtime above because injection state is only known then.
  return security === "none" ? "globals-then-library" : "nothing";
}
