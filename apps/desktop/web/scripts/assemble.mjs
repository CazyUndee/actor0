#!/usr/bin/env node
/**
 * Assembles the two halves into the layout the shell serves.
 *
 * `resources/app` is the UI bundle (built by vite), and `resources/agent` is the
 * agent bundle (built by `@actor0/desktop-agent`). Keeping the copy in one small
 * script — rather than two `cp` calls in a package.json string — is what makes
 * the layout a single readable fact, since the shell's config, the spawn command
 * and `neu build` all depend on it being exactly this.
 *
 * It also *generates* `resources/app/neutralino-loader.inline.js`: the same
 * decision table the tests exercise, so the page's loader and the tested policy
 * cannot drift apart. That is the NE_CL_IVCTOKN lesson — half the fix's value is
 * the policy being written down somewhere that breaks loudly when violated.
 *
 * This runs as part of `npm run build` (see package.json) because `vite build`
 * empties `resources/app`: without it the generated loader and the client
 * library vanish after every build, the page 404s on the loader, `NL_MODE` is
 * never defined, and every window.* call silently becomes a no-op.
 */

import { cpSync, existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const webRoot = join(here, "..");
const agentDist = join(webRoot, "..", "agent", "dist", "agent.mjs");
const agentTarget = join(webRoot, "resources", "agent");

if (!existsSync(agentDist)) {
  console.error(`missing ${agentDist} — run: npm --workspace @actor0/desktop-agent run build`);
  process.exit(1);
}

rmSync(agentTarget, { recursive: true, force: true });
mkdirSync(agentTarget, { recursive: true });
cpSync(agentDist, join(agentTarget, "agent.mjs"));

// The Neutralino client library, served beside the page so the same bundle
// works when the shell does not inject it (dev mode through the static server).
const clientLib = join(webRoot, "..", "..", "..", "node_modules", "@neutralinojs", "lib", "dist", "neutralino.js");
if (existsSync(clientLib)) {
  cpSync(clientLib, join(webRoot, "resources", "app", "neutralino.js"));
}

const ui = join(webRoot, "resources", "app", "index.html");
if (!existsSync(ui)) {
  console.error(`missing ${ui} — run: npm --workspace @actor0/desktop-web run build`);
  process.exit(1);
}

const security = readTokenSecurity();
const order = decideOrder(security);
writeFileSync(join(webRoot, "resources", "app", "neutralino-loader.inline.js"), renderLoader(security, order));

console.log("resources/ ready: app/ (UI) + agent/agent.mjs (agent core)");

function readTokenSecurity() {
  const config = JSON.parse(readFileSync(join(webRoot, "neutralino.config.json"), "utf8"));
  return config.tokenSecurity === "none" ? "none" : "one-time";
}

function decideOrder(sec) {
  // Mirrors decideClientLoad's no-injection branch; the injected branch is
  // handled at runtime below because injection state is only known then.
  return sec === "none" ? "globals-then-library" : "nothing";
}

/**
 * The page-side loader.
 *
 * Two plain document.write calls, in order: globals first (they define
 * NL_TOKEN/NL_PORT/NL_MODE), then the client library. There is deliberately no
 * nested write — a document.write inside a script that document.write itself
 * inserted silently does nothing once the parser has moved past it, which is how
 * the library once went missing and every window.* call became a no-op while
 * the page looked perfectly healthy.
 *
 * `</script>` is split across a concatenation so this file's own parsing is not
 * ended by the tag it is writing.
 */
function renderLoader(sec, ord) {
  // The written markup must be exactly `<script src="PATH"></script>`. Both
  // halves are emitted as single JS string literals so the generator stays
  // readable; the shape is asserted afterwards, because a malformed tag does
  // not fail loudly — it parses as one unterminated attribute and swallows
  // the rest of the document (which is how the library once went missing
  // while the page still looked healthy).
  const openSrc = JSON.stringify('<scr' + 'ipt src="');
  const closeSrc = JSON.stringify('">' + '</scr' + 'ipt>');
  const probe = JSON.parse(openSrc) + '/x' + JSON.parse(closeSrc);
  if (probe !== '<script src="/x"></script>') {
    throw new Error(`loader tag is malformed: ${JSON.stringify(probe)}`);
  }
  return [
    "// GENERATED by scripts/assemble.mjs — edit src/neutralino-loader.ts instead.",
    `// tokenSecurity in neutralino.config.json is ${JSON.stringify(sec)}.`,
    "(function () {",
    `  var OPEN = ${openSrc};`,
    `  var CLOSE = ${closeSrc};`,
    '  if (typeof window.NL_TOKEN !== "undefined" && window.NL_TOKEN !== "") {',
    "    // The shell injected a real token; only the library may be missing.",
    '    if (typeof window.Neutralino === "undefined") {',
    '      document.write(OPEN + "/neutralino.js" + CLOSE);',
    "    }",
    "    return;",
    "  }",
    `  if (${JSON.stringify(ord)} === "nothing") return; // see neutralino-loader.ts: refuse to load`,
    '  document.write(OPEN + "/__neutralino_globals.js" + CLOSE);',
    '  document.write(OPEN + "/neutralino.js" + CLOSE);',
    "})();",
    "",
  ].join("\n");
}
